; ============================================================
; ■ MN1610互換命令（メモリ参照: L / ST / B / BAL / IMS / DMS）
;   アドレッシングモード 8種すべてを検証する
; ============================================================

; ── L命令（ロード）──────────────────────────────────────────
; MMM=000 ゼロページ直接
        L   R0, *ZPADDR         ; R0 ← (ZPADDR)
        L   R1, *ZPADDR
        L   R2, *ZPADDR
        L   R3, *ZPADDR
        L   R4, *ZPADDR
        L   SP, *ZPADDR

; MMM=001 相対直接（ラベルが相対範囲内にある前提）
        L   R0, RELDATA         ; R0 ← (相対アドレス)
        L   R1, RELDATA

; MMM=010 ゼロページ間接
        L   R0, [*ZPPTR]        ; R0 ← ((ZPPTR))
        L   R2, [*ZPPTR]

; MMM=011 相対間接
        L   R0, [RELPTR]        ; R0 ← ((相対アドレス))
        L   R3, [RELPTR]

; MMM=100 直接インデックス0（X0=R3）
        L   R0, 5, X0           ; R0 ← ((X0) + 5)
        L   R1, 10, X0
        L   R0, 0, X0

; MMM=101 直接インデックス1（X1=R4）
        L   R0, 5, X1           ; R0 ← ((X1) + 5)
        L   R2, 10, X1
        L   R0, 0, X1

; MMM=110 間接インデックス0
        L   R0, [*ZPADDR], X0   ; R0 ← ((X0) + [ZPADDR])
        L   R1, [*ZPADDR], X0

; MMM=111 間接インデックス1
        L   R0, [*ZPADDR], X1   ; R0 ← ((X1) + [ZPADDR])
        L   R2, [*ZPADDR], X1

; ── ST命令（ストア）─────────────────────────────────────────
        ST  R0, *ZPADDR
        ST  R1, *ZPADDR
        ST  R2, *ZPADDR
        ST  R3, *ZPADDR
        ST  R4, *ZPADDR
        ST  SP, *ZPADDR
        ST  R0, RELDATA
        ST  R0, [*ZPPTR]
        ST  R0, [RELPTR]
        ST  R0, 5, X0
        ST  R0, 5, X1
        ST  R0, [*ZPADDR], X0
        ST  R0, [*ZPADDR], X1

; ── B命令（無条件分岐）──────────────────────────────────────
        B   *ZPADDR             ; ゼロページ直接
        B   BREL_TARGET         ; 相対直接
        B   [*ZPPTR]            ; ゼロページ間接
        B   [BREL_IND]          ; 相対間接
        B   5, X0               ; 直接インデックス0
        B   5, X1               ; 直接インデックス1
        B   [*ZPADDR], X0       ; 間接インデックス0
        B   [*ZPADDR], X1       ; 間接インデックス1

BREL_TARGET:
BREL_IND:

; ── BAL命令（サブルーチン呼び出し）─────────────────────────
        BAL *ZPADDR             ; ゼロページ直接
        BAL BALREL_TARGET       ; 相対直接
        BAL [*ZPPTR]            ; ゼロページ間接
        BAL [BALREL_IND]        ; 相対間接
        BAL 5, X0               ; 直接インデックス0
        BAL 5, X1               ; 直接インデックス1
        BAL [*ZPADDR], X0       ; 間接インデックス0
        BAL [*ZPADDR], X1       ; 間接インデックス1

BALREL_TARGET:
BALREL_IND:

; ── IMS命令（メモリインクリメント&スキップ）─────────────────
        IMS *ZPADDR             ; ゼロページ直接
        IMS IMSREL              ; 相対直接
        IMS [*ZPPTR]            ; ゼロページ間接
        IMS [IMSRELI]           ; 相対間接
        IMS 2, X0               ; 直接インデックス0
        IMS 2, X1               ; 直接インデックス1
        IMS [*ZPADDR], X0       ; 間接インデックス0
        IMS [*ZPADDR], X1       ; 間接インデックス1

IMSREL:
IMSRELI:

; ── DMS命令（メモリデクリメント&スキップ）─────────────────
        DMS *ZPADDR
        DMS DMSREL
        DMS [*ZPPTR]
        DMS [DMSRELI]
        DMS 2, X0
        DMS 2, X1
        DMS [*ZPADDR], X0
        DMS [*ZPADDR], X1

DMSREL:
DMSRELI:

