OPSW0S: .word 0             ; レベル0 STR退避
OPSW0I: .word 0             ; レベル0 IC退避
OPSW1S: .word 0             ; レベル1 STR退避
OPSW1I: .word 0             ; レベル1 IC退避
OPSW2S: .word 0             ; レベル2 STR退避
OPSW2I: .word 0             ; レベル2 IC退避

; 相対アドレッシングテスト用データ（アドレス 0x06, 0x07）
; ← PSW直後に置くことで、L/ST命令の相対オフセット範囲内に収める
RELDATA: .word 0x1234           ; 相対直接参照用データ
RELPTR:  .word RELDATA          ; 相対間接参照用ポインタ（=0x0006）

