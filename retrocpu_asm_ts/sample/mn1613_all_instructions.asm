; ■ MN1610互換命令（レジスタ間演算）2項演算命令
; ============================================================

; ── A命令（加算） ────────────────────────────────────────────
        A   R0, R1
        A   R0, R2
        A   R0, R3
        A   R0, R4
        A   R0, SP
        A   R0, STR
        A   R1, R0
        A   R2, R3
        A   SP, R1
        A   STR, R0

; ── S命令（減算） ────────────────────────────────────────────
        S   R0, R1
        S   R0, R2
        S   R1, R2
        S   R2, SP

; ── C命令（比較 16bit） ──────────────────────────────────────
        C   R0, R1
        C   R1, R2
        C   R2, R3
        C   SP, R0

; ── CB命令（比較 下位8bit） ──────────────────────────────────
        CB  R0, R1
        CB  R1, R2

; ── MV命令（転送 16bit） ─────────────────────────────────────
        MV  R0, R1
        MV  R1, R0
        MV  STR, R0
        MV  R0, STR

; ── MVB命令（転送 下位8bit） ─────────────────────────────────
        MVB R0, R1
        MVB R1, R2

; ── BSWP命令（バイトスワップ転送） ──────────────────────────
        BSWP R0, R1
        BSWP R0, R0             ; 自己スワップ（上下バイト交換）
        BSWP R1, R2

; ── DSWP命令（デジットスワップ転送） ────────────────────────
        DSWP R0, R1
        DSWP R0, R0             ; 自己スワップ
        DSWP R2, R3

; ── LAD命令（BCD補正値ロード） ──────────────────────────────
        LAD  R0, R1
        LAD  R1, R2
        LAD  R2, R3

; ── AND命令（論理積） ────────────────────────────────────────
        AND  R0, R1
        AND  R1, R2
        AND  R2, R3

; ── OR命令（論理和） ─────────────────────────────────────────
        OR   R0, R1
        OR   R1, R2
        OR   R2, R3

; ── EOR命令（排他的論理和） ─────────────────────────────────
        EOR  R0, R1
        EOR  R0, R0             ; CLRの代用（R0=0）
        EOR  R1, R1             ; R1=0
        EOR  R2, R3

; ============================================================
; ■ スキップ条件 全16種（A R0, R1 で代表検証）
; ============================================================
        A   R0, R1              ; スキップなし（省略）
        A   R0, R1, SKP         ; 無条件スキップ
        A   R0, R1, M           ; 結果が負
        A   R0, R1, PZ          ; 結果が正または零
        A   R0, R1, Z           ; 結果が零
        A   R0, R1, E           ; 結果が零（Zの別名）
        A   R0, R1, NZ          ; 結果が零でない
        A   R0, R1, NE          ; 結果が零でない（NZの別名）
        A   R0, R1, MZ          ; 結果が負または零
        A   R0, R1, P           ; 結果が正
        A   R0, R1, EZ          ; Eレジスタが零
        A   R0, R1, ENZ         ; Eレジスタが零でない
        A   R0, R1, OZ          ; Vフラグが零
        A   R0, R1, ONZ         ; Vフラグが零でない
        A   R0, R1, LMZ         ; 無符号で≦
        A   R0, R1, LP          ; 無符号で＞
        A   R0, R1, LPZ         ; 無符号で≧
        A   R0, R1, LM          ; 無符号で＜

; ── スキップ条件を他の演算命令でも確認 ──────────────────────
        S   R0, R1, Z
        C   R0, R1, LP
        CB  R0, R1, Z
        MV  R0, R1, EZ
        AND R0, R1, NZ
        OR  R0, R1, M
        EOR R0, R1, SKP
        LAD R0, R1, Z
        BSWP R0, R1, Z
        DSWP R0, R1, P

