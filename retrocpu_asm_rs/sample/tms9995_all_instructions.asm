; ============================================================
; TMS9995 全命令・全アドレッシングモード 網羅テスト
;
; 根拠: .cursor/rules/TMS9995_instruction.mdc / asm_rules.mdc
; 構文は sdas（TI の *R / @addr / >xxxx は使わない）
;
; 実行可能なプログラムであることより、全組み合わせの受理を優先する。
; アセンブル: npm run assemble -- sample/tms9995_all_instructions.asm
; ============================================================

	.cpu	tms9995

	.org	0x1000

START:

; ============================================================
; Format 1（双オペランド）アドレッシング 5 種
;   Rn / (Rn) / (Rn)+ / ラベル / addr(Rn)
; MOV で全組み合わせ、他は R1,R2 を 1 回ずつ
; ============================================================

	MOV	R1, R2
	MOV	(R3), R0
	MOV	(R4)+, R1
	MOV	DATA, R0
	MOV	IDX(R1), R2
	MOV	R3, (R5)
	MOV	R3, (R6)+
	MOV	R3, DATA
	MOV	R3, IDX(R2)
	MOV	(R7), (R8)
	MOV	(R7)+, DATA
	MOV	DATA, IDX(R3)
	MOV	IDX(R4), (R9)+
	MOV	[R10], R0

	SZC	R1, R2
	SZCB	R1, R2
	S	R1, R2
	SB	R1, R2
	C	R1, R2
	CB	R1, R2
	A	R1, R2
	AB	R1, R2
	MOVB	R1, R2
	SOC	R1, R2
	SOCB	R1, R2

; ============================================================
; Format 2 条件ジャンプ（相対。次命令＝変位 0）
; ============================================================

	JMP	L_JMP
L_JMP:	JLT	L_JLT
L_JLT:	JLE	L_JLE
L_JLE:	JEQ	L_JEQ
L_JEQ:	JHE	L_JHE
L_JHE:	JGT	L_JGT
L_JGT:	JNE	L_JNE
L_JNE:	JNC	L_JNC
L_JNC:	JOC	L_JOC
L_JOC:	JNO	L_JNO
L_JNO:	JL	L_JL
L_JL:	JH	L_JH
L_JH:	JOP	L_JOP
L_JOP:

; Format 2 CRU（R12 相対。#disp）
	SBO	#0
	SBZ	#1
	TB	#-1
	SBO	#127
	SBZ	#-128

; ============================================================
; Format 3 COC / CZC / XOR（src 汎用, dst は Rn）
; ============================================================

	COC	R1, R2
	CZC	(R3), R4
	XOR	(R5)+, R6
	COC	DATA, R7
	CZC	IDX(R1), R8

; ============================================================
; Format 4 LDCR / STCR（addr, #bits。0 と 16 は 16bit）
; ============================================================

	LDCR	R1, #8
	STCR	R2, #16
	LDCR	(R3), #1
	STCR	(R4)+, #0
	LDCR	DATA, #16
	STCR	IDX(R1), #9

; ============================================================
; Format 5 シフト（Rn, #count。0 は R0 下位 4bit）
; ============================================================

	SRA	R1, #0
	SRL	R1, #1
	SLA	R2, #2
	SRC	R15, #15

; ============================================================
; Format 6 単オペランド（汎用アドレス）
; ============================================================

	BLWP	R0
	B	R0
	X	R0
	CLR	R0
	NEG	R1
	INV	R2
	INC	R3
	INCT	R4
	DEC	R5
	DECT	R6
	BL	R7
	SWPB	R8
	SETO	R9
	ABS	R10
	DIVS	R0
	MPYS	R0

	CLR	(R11)
	CLR	(R12)+
	CLR	DATA
	CLR	IDX(R1)
	B	START
	BL	SUB
	BLWP	DATA
	X	DATA
	DIVS	(R1)+
	MPYS	IDX(R2)

; ============================================================
; Format 7 外部／特殊
; ============================================================

	IDLE
	RSET
	RTWP
	CKON
	CKOF
	LREX

; ============================================================
; Format 8 即値／ワークスペース
; ============================================================

	LI	R1, #0x1234
	AI	R0, #1
	ANDI	R2, #0x00FF
	ORI	R3, #0x8000
	CI	R1, #0x0100
	LWPI	#WS
	LIMI	#2
	STWP	R13
	STST	R15
	LST	R15
	LWP	R13

; ============================================================
; Format 9 MPY / DIV / XOP
; ============================================================

	MPY	R1, R2
	DIV	R1, R2
	XOP	R1, #3
	MPY	DATA, R4
	DIV	(R5)+, R6
	XOP	IDX(R1), #15

; ============================================================
; 別名
; ============================================================

	RT
	NOP

SUB:	CLR	R0
	B	(R11)

; ============================================================
; データ（シンボリック／インデックス用）
; ============================================================

DATA:	.word	0xABCD
IDX:	.word	0
WS:	.blkw	16
